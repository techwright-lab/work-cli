    def mock_build(self, fail_dependencies=False, cargo_manifest=GIT_CARGO,
                   cargo_lock=GITCORE_LOCK, cargo_version="1.98.1", mutate_tool_after_make=False):
        (self.source / ".gitignore").write_text("/target\n")
        sdk = self.root / "sdk"
        sdk.mkdir()
        cc = self.root / "clang"
        cc.write_text("mock compiler")
        cc.chmod(0o700)
        for name in ("make", "lipo", "otool", "ar", "ld"):
            (self.root / name).write_text("mock existing tool")
            (self.root / name).chmod(0o700)
        toolchain = self.root / "pinned-toolchain"
        (toolchain / "bin").mkdir(parents=True)
        for name in ("cargo", "rustc", "rustdoc"):
            path = toolchain / "bin" / name
            path.write_text("mock native pinned tool")
            path.chmod(0o700)
        archive = self.archive([("git-2.55.0/Makefile", "file", b"all:\n"),
                                ("git-2.55.0/Cargo.toml", "file", cargo_manifest)])
        archive.chmod(0o444)
        options = SimpleNamespace(source=self.source, destination=self.destination,
                                  source_revision="1" * 40, version="2.55.0",
                                  sdk_root=sdk, cc=cc, archive=archive, toolchain_dir=toolchain)
        commands = []
        self.commands = commands

        def observe(command, env, destination):
            command = [str(arg) for arg in command]
            commands.append(command)
            name = Path(command[0]).name
            if name == "cargo":
                if "generate-lockfile" in command:
                    self.assertEqual(env["CARGO_NET_OFFLINE"], "true")
                    self.assertEqual(Path(command[command.index("--manifest-path") + 1]), self.destination / "Cargo.toml")
                    self.assertEqual(destination, self.destination)
                    (self.destination / "Cargo.lock").write_bytes(cargo_lock)
                    return ""
                return "cargo " + cargo_version + " (mock)"
            if name == "rustc":
                return "rustc 1.98.1 (mock)\nrelease: 1.98.1\nhost: aarch64-apple-darwin"
            if name == "rustdoc":
                return "rustdoc 1.98.1 (mock)"
            if name == "file":
                return "Mach-O 64-bit executable arm64"
            if name == "lipo":
                return "arm64"
            if name == "uname":
                return "Darwin" if command[-1] == "-s" else "arm64"
            if name == "sw_vers":
                return "27.0.1"
            if name == "sysctl":
                return "0"
            if name == "clang" and "-o" in command and fail_dependencies:
                raise self.builder.Refusal("failed probe")
            if name == "make" and "install" in command:
                self.make_environment = dict(env)
                prefix = self.destination / "prefix"
                for relative in ["bin/git", *["libexec/git-core/" + n for n in self.builder.HELPERS]]:
                    path = prefix / relative
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text("mock Mach-O")
                    path.chmod(0o700)
                if mutate_tool_after_make:
                    (toolchain / "bin/rustc").write_text("changed during make")
            if name == "git":
                return "git version 2.55.0" if command[-1] == "--version" else str(self.destination / "prefix/libexec/git-core")
            return "mock dependency version"

        def executable(path, env, destination, lipo=None):
            return dict(self.builder.file_identity(path), architecture="arm64")

        with mock.patch.dict(self.builder.PINS, {"2.55.0": hashlib.sha256(archive.read_bytes()).hexdigest()}), \
                mock.patch.object(self.builder, "observe", side_effect=observe), \
                mock.patch.object(self.builder, "native_executable", side_effect=executable):
            self.builder.build(options)
        return commands

