    def archive(self, members=None):
        path = self.root / "archive.tar.xz"
        with tarfile.open(path, "w:xz") as archive:
            for name, kind, content in members or [("git-2.55.0/Makefile", "file", b"all:\n")]:
                member = tarfile.TarInfo(name)
                member.mode = 0o755 if name.endswith("script") else 0o644
                if kind == "file":
                    member.size = len(content)
                    archive.addfile(member, io.BytesIO(content))
                else:
                    member.type = {"symlink": tarfile.SYMTYPE, "hardlink": tarfile.LNKTYPE,
                                   "fifo": tarfile.FIFOTYPE, "directory": tarfile.DIRTYPE}[kind]
                    if kind in ("symlink", "hardlink"):
                        member.linkname = content
                    archive.addfile(member)
        return path

